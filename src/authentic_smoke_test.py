# 1. GARCH(1,1) synthetic data generator
# ============================================================================
def garch11(n: int, omega: float, alpha: float, beta: float,
            rng: np.random.Generator) -> np.ndarray:
    """
    Generate log returns from a GARCH(1,1) process.
    Volatility clustering + heavy tails are emergent properties.
    """
    eps = np.zeros(n)
    sigma2 = np.zeros(n)
    sigma2[0] = omega / max(1.0 - alpha - beta, 1e-6)
    for t in range(1, n):
        sigma2[t] = omega + alpha * eps[t - 1] ** 2 + beta * sigma2[t - 1]
        eps[t] = np.sqrt(sigma2[t]) * rng.standard_t(df=5.0) / np.sqrt(5.0 / 3.0)
    return eps


# Asset-calibrated GARCH parameters (commonly cited values in literature)
ASSET_CONFIG = {
    "EQUITY_MID":   dict(omega=2.0e-6, alpha=0.08, beta=0.90),   # ~24% ann vol
    "EQUITY_HIGH":  dict(omega=1.5e-5, alpha=0.10, beta=0.85),   # ~48% ann vol
    "CRYPTO":       dict(omega=8.0e-5, alpha=0.14, beta=0.82),   # ~75% ann vol
}


def make_dataset(asset_class: str, n: int = 600, seed: int = 0):
    """Return (X, y) sequences with sequence length 30 and 4 features."""
    cfg = ASSET_CONFIG[asset_class]
    rng = np.random.default_rng(seed)
    rets = garch11(n + 60, **cfg, rng=rng)
    rets = rets[60:]                                # warm-up burn-in
    # Features: lagged returns, sign of return, abs(return), rolling mean(5)
    abs_ret = np.abs(rets)
    sign_ret = np.sign(rets)
    roll = np.convolve(rets, np.ones(5) / 5, mode="same")
    feats = np.stack([rets, sign_ret, abs_ret, roll], axis=1)

    # Min-max scale to [-1, 1] using train portion only
    n_train = int(0.7 * len(feats))
    f_min = feats[:n_train].min(axis=0)
    f_max = feats[:n_train].max(axis=0)
    feats_n = 2.0 * (feats - f_min) / (f_max - f_min + 1e-12) - 1.0

    # Build (T=30) -> (next-step return) sequences
    SEQ = 30
    X, y = [], []
    for i in range(len(feats_n) - SEQ - 1):
        X.append(feats_n[i : i + SEQ])
        y.append(rets[i + SEQ + 1])
    X = np.array(X, dtype=np.float64)
    y = np.array(y, dtype=np.float64)
    return X, y, n_train


# ============================================================================
# 2. 4-qubit state-vector VQC simulator (pure numpy)
# ============================================================================
N_QUBITS = 4
DIM = 1 << N_QUBITS                                  # 16

# Pre-compute per-qubit Z-sign vectors for measurement
_Z_SIGNS = np.zeros((N_QUBITS, DIM))
for w in range(N_QUBITS):
    for i in range(DIM):
        bit = (i >> (N_QUBITS - 1 - w)) & 1
        _Z_SIGNS[w, i] = 1.0 if bit == 0 else -1.0


def _apply_1q(psi: np.ndarray, U: np.ndarray, wire: int) -> np.ndarray:
    """Fast single-qubit gate via tensor reshape (no 16x16 matrix build)."""
    # psi has shape (2, 2, 2, 2) when reshaped
    t = psi.reshape([2] * N_QUBITS)
    t = np.moveaxis(t, wire, 0)              # (2, ...)
    out = np.einsum("ij,j...->i...", U, t)
    out = np.moveaxis(out, 0, wire)
    return out.reshape(DIM)


def _apply_cnot(psi: np.ndarray, ctrl: int, tgt: int) -> np.ndarray:
    """Apply CNOT(ctrl, tgt) by index swap on the affected basis states."""
    t = psi.reshape([2] * N_QUBITS).copy()
    # When ctrl bit is 1, flip target bit
    idx = [slice(None)] * N_QUBITS
    idx[ctrl] = 1
    # Swap target axis values 0 and 1 at ctrl=1
    sub = t[tuple(idx)]                       # ctrl=1 sub-tensor
    sub = np.flip(sub, axis=tgt if tgt < ctrl else tgt - 1)
    t[tuple(idx)] = sub
    return t.reshape(DIM)


# Pre-compiled 1-qubit gate matrices
_H = np.array([[1, 1], [1, -1]], dtype=complex) / np.sqrt(2.0)


def _U_rx(theta: float) -> np.ndarray:
    c, s = np.cos(theta / 2), np.sin(theta / 2)
    return np.array([[c, -1j * s], [-1j * s, c]], dtype=complex)


def _U_ry(theta: float) -> np.ndarray:
    c, s = np.cos(theta / 2), np.sin(theta / 2)
    return np.array([[c, -s], [s, c]], dtype=complex)


def _U_rz(theta: float) -> np.ndarray:
    return np.diag([np.exp(-1j * theta / 2), np.exp(1j * theta / 2)]).astype(complex)


def vqc_expvals(x: np.ndarray, weights: np.ndarray) -> np.ndarray:
    """
    Run the variational quantum circuit via direct state-vector simulation.
    x: (4,) input in [-1,1], weights: (n_blocks, 4, 3), returns (4,) <Z_w>.
    """
    psi = np.zeros(DIM, dtype=complex); psi[0] = 1.0
    # ---- encoding (Hadamard + RY(2x_i)) ----
    for w in range(N_QUBITS):
        psi = _apply_1q(psi, _H, w)
        psi = _apply_1q(psi, _U_ry(2.0 * float(x[w])), w)
    # ---- variational blocks ----
    for b in range(weights.shape[0]):
        for w in range(N_QUBITS):
            psi = _apply_1q(psi, _U_rx(float(weights[b, w, 0])), w)
            psi = _apply_1q(psi, _U_ry(float(weights[b, w, 1])), w)
            psi = _apply_1q(psi, _U_rz(float(weights[b, w, 2])), w)
        for w in range(N_QUBITS):
            psi = _apply_cnot(psi, w, (w + 1) % N_QUBITS)
    # ---- measurement ----
    probs = (psi.conj() * psi).real
    return _Z_SIGNS @ probs


