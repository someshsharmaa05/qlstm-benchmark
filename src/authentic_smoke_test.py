# 7. Main: small 2-asset x 2-model x 3-seed authentic experiment
# ============================================================================
def main(out_path: Path = Path("results/raw/smoke_test_real.json")):
    print("="*78)
    print("AUTHENTIC NUMPY-ONLY SMOKE TEST — proof-of-concept QLSTM benchmark")
    print("="*78)
    print("This produces REAL numbers from REAL computation in this environment.")
    print("It is NOT a replacement for the full Yahoo Finance experiment.")
    print()

    assets = ["EQUITY_HIGH", "CRYPTO"]
    models = ["lstm", "qlstm"]
    seeds  = [42, 137, 271]

    all_results = []
    t_global = time.time()
    for asset in assets:
        print(f"\n--- asset class: {asset} ---")
        for model_kind in models:
            print(f"  {model_kind}: ", end="", flush=True)
            for seed in seeds:
                r = run_one(asset, model_kind, seed,
                            n=240, n_iter=30 if model_kind == "lstm" else 20)
                all_results.append(r)
                print(f"seed={seed} rmse={r['rmse']:.4f} da={r['da']:.1f}% "
                      f"params={r['n_params']} t={r['train_sec']:.1f}s | ",
                      end="", flush=True)
            print()
    total = time.time() - t_global

    # Aggregate
    summary = {}
    for asset in assets:
        summary[asset] = {}
        for model_kind in models:
            rs = [r for r in all_results if r["asset"] == asset and r["model"] == model_kind]
            rmses = np.array([r["rmse"] for r in rs])
            das   = np.array([r["da"]   for r in rs])
            summary[asset][model_kind] = {
                "rmse_mean": float(rmses.mean()), "rmse_std": float(rmses.std()),
                "da_mean":   float(das.mean()),
                "n_seeds": len(rs),
            }

    # Wilcoxon QLSTM vs LSTM
    pvals = {}
    for asset in assets:
        ql = sorted([r for r in all_results if r["asset"] == asset and r["model"] == "qlstm"],
                    key=lambda r: r["seed"])
        ls = sorted([r for r in all_results if r["asset"] == asset and r["model"] == "lstm"],
                    key=lambda r: r["seed"])
        a = np.array([r["rmse"] for r in ql])
        b = np.array([r["rmse"] for r in ls])
        try:
            _, p = stats.wilcoxon(a, b, alternative="two-sided")
            pvals[asset] = float(p)
        except Exception:
            pvals[asset] = None

    print("\n" + "="*78)
    print("SUMMARY (3 seeds, 30 SPSA iterations, 4-qubit state-vector QLSTM)")
    print("="*78)
    for asset in assets:
        s = summary[asset]
        print(f"\n  {asset}")
        print(f"    LSTM     RMSE = {s['lstm']['rmse_mean']:.4f} ± {s['lstm']['rmse_std']:.4f}  "
              f"DA = {s['lstm']['da_mean']:.1f}%")
        print(f"    QLSTM    RMSE = {s['qlstm']['rmse_mean']:.4f} ± {s['qlstm']['rmse_std']:.4f}  "
              f"DA = {s['qlstm']['da_mean']:.1f}%")
        print(f"    Wilcoxon p = {pvals[asset]}")
    print(f"\n  Total wall-clock: {total:.1f} sec")
    print("="*78)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps({
        "results": all_results, "summary": summary, "wilcoxon_p": pvals,
        "wall_clock_sec": total,
        "note": ("Authentic numpy-only smoke test on synthetic GARCH(1,1) data. "
                 "Not a substitute for the full Yahoo Finance benchmark — "
                 "those numbers must be produced by running qlstm_pkg with "
                 "torch and pennylane on a machine with internet access."),
    }, indent=2))
    print(f"\nWrote {out_path}")
    return summary, pvals


if __name__ == "__main__":
    main()
