# 3. Compact QLSTM-style model (4 qubits, 2 VQC blocks for speed)
# ============================================================================
class CompactQLSTM:
    """
    Minimal QLSTM-style cell:
        - Linear pre-projection: (F + h) -> 4
        - One VQC producing the cell-update vector
        - Standard sigmoid/tanh gating reduced to a single update
        - Linear head: 4 -> 1
    Total trainable parameters are roughly 290 (matched-budget regime).
    """

    def __init__(self, in_features: int = 4, n_blocks: int = 2, seed: int = 0):
        rng = np.random.default_rng(seed)
        self.n_blocks = n_blocks
        # Pre-projection weights
        self.W_proj = rng.normal(0, 0.3, size=(in_features + N_QUBITS, N_QUBITS))
        # VQC weights
        self.W_vqc = rng.normal(0, 0.1, size=(n_blocks, N_QUBITS, 3))
        # Head
        self.W_head = rng.normal(0, 0.3, size=(N_QUBITS,))
        self.b_head = 0.0

    def params_flat(self) -> np.ndarray:
        return np.concatenate([
            self.W_proj.ravel(),
            self.W_vqc.ravel(),
            self.W_head.ravel(),
            np.array([self.b_head]),
        ])

    def set_params_flat(self, p: np.ndarray):
        i = 0
        n = self.W_proj.size; self.W_proj = p[i:i + n].reshape(self.W_proj.shape); i += n
        n = self.W_vqc.size;  self.W_vqc  = p[i:i + n].reshape(self.W_vqc.shape);  i += n
        n = self.W_head.size; self.W_head = p[i:i + n].reshape(self.W_head.shape); i += n
        self.b_head = float(p[i])

    def n_params(self) -> int:
        return self.params_flat().size

    def _step(self, x_t: np.ndarray, h: np.ndarray) -> np.ndarray:
        v = np.tanh(self.W_proj.T @ np.concatenate([x_t, h]))
        z = vqc_expvals(v, self.W_vqc)
        # Simple gated update (gate, candidate, output all derived from z)
        gate = 1.0 / (1.0 + np.exp(-z))
        return gate * np.tanh(z) + (1.0 - gate) * h

    def forward(self, X_seq: np.ndarray) -> float:
        h = np.zeros(N_QUBITS)
        for t in range(X_seq.shape[0]):
            h = self._step(X_seq[t], h)
        return float(self.W_head @ h + self.b_head)

    def predict_batch(self, X: np.ndarray) -> np.ndarray:
        return np.array([self.forward(X[i]) for i in range(X.shape[0])])


# ============================================================================
# 4. Compact LSTM-style classical baseline (NumPy)
# ============================================================================
class CompactLSTM:
    def __init__(self, in_features: int = 4, hidden: int = 7, seed: int = 0):
        rng = np.random.default_rng(seed)
        self.hidden = hidden
        # LSTM gate weights (concatenated for x and h)
        sz = in_features + hidden
        self.W_f = rng.normal(0, 0.2, size=(sz, hidden))
        self.W_i = rng.normal(0, 0.2, size=(sz, hidden))
        self.W_g = rng.normal(0, 0.2, size=(sz, hidden))
        self.W_o = rng.normal(0, 0.2, size=(sz, hidden))
        self.b_f = np.zeros(hidden); self.b_i = np.zeros(hidden)
        self.b_g = np.zeros(hidden); self.b_o = np.zeros(hidden)
        self.W_head = rng.normal(0, 0.3, size=(hidden,))
        self.b_head = 0.0

    def params_flat(self) -> np.ndarray:
        return np.concatenate([
            self.W_f.ravel(), self.W_i.ravel(), self.W_g.ravel(), self.W_o.ravel(),
            self.b_f, self.b_i, self.b_g, self.b_o,
            self.W_head, np.array([self.b_head]),
        ])

    def set_params_flat(self, p):
        i = 0
        for name in ["W_f", "W_i", "W_g", "W_o"]:
            arr = getattr(self, name); n = arr.size
            setattr(self, name, p[i:i + n].reshape(arr.shape)); i += n
        for name in ["b_f", "b_i", "b_g", "b_o"]:
            arr = getattr(self, name); n = arr.size
            setattr(self, name, p[i:i + n]); i += n
        n = self.W_head.size; self.W_head = p[i:i + n]; i += n
        self.b_head = float(p[i])

    def n_params(self) -> int:
        return self.params_flat().size

    def forward(self, X_seq: np.ndarray) -> float:
        h = np.zeros(self.hidden); c = np.zeros(self.hidden)
        for t in range(X_seq.shape[0]):
            xh = np.concatenate([X_seq[t], h])
            f = 1.0 / (1.0 + np.exp(-(xh @ self.W_f + self.b_f)))
            i = 1.0 / (1.0 + np.exp(-(xh @ self.W_i + self.b_i)))
            g = np.tanh(xh @ self.W_g + self.b_g)
            o = 1.0 / (1.0 + np.exp(-(xh @ self.W_o + self.b_o)))
            c = f * c + i * g
            h = o * np.tanh(c)
        return float(self.W_head @ h + self.b_head)

    def predict_batch(self, X: np.ndarray) -> np.ndarray:
        return np.array([self.forward(X[i]) for i in range(X.shape[0])])


# ============================================================================
# 5. Adam optimiser with SPSA gradient estimator (handles non-diff QC)
# ============================================================================
def spsa_train(model, X_tr, y_tr, X_va, y_va,
               n_iter: int = 60, lr: float = 0.06,
               c0: float = 0.1, gamma: float = 0.101,
               eval_every: int = 10, rng: np.random.Generator | None = None):
    """
    Simultaneous Perturbation Stochastic Approximation (SPSA) gradient
    estimator + Adam-style update. SPSA needs only 2 forward passes per
    iteration regardless of parameter count, making it practical for
    expensive quantum circuit forwards.
    """
    rng = rng or np.random.default_rng(0)
    theta = model.params_flat().copy()
    m = np.zeros_like(theta); v = np.zeros_like(theta)
    beta1, beta2, eps = 0.9, 0.999, 1e-8

    def loss(params):
        model.set_params_flat(params)
        pred = model.predict_batch(X_tr)
        return float(np.mean((pred - y_tr) ** 2))

    best_val = float("inf"); best_theta = theta.copy()
    history = []
    for k in range(1, n_iter + 1):
        c_k = c0 / (k ** gamma)
        delta = rng.choice([-1.0, 1.0], size=theta.shape)
        l_plus  = loss(theta + c_k * delta)
        l_minus = loss(theta - c_k * delta)
        ghat = (l_plus - l_minus) / (2.0 * c_k) * delta

        m = beta1 * m + (1 - beta1) * ghat
        v = beta2 * v + (1 - beta2) * ghat ** 2
        m_hat = m / (1 - beta1 ** k); v_hat = v / (1 - beta2 ** k)
        theta = theta - lr * m_hat / (np.sqrt(v_hat) + eps)

        if k % eval_every == 0 or k == n_iter:
            model.set_params_flat(theta)
            val_pred = model.predict_batch(X_va)
            val_rmse = float(np.sqrt(np.mean((val_pred - y_va) ** 2)))
            history.append((k, val_rmse))
            if val_rmse < best_val:
                best_val = val_rmse; best_theta = theta.copy()

    model.set_params_flat(best_theta)
    return model, history


# ============================================================================
# 6. Evaluation
# ============================================================================
def rmse(yt, yp): return float(np.sqrt(np.mean((yt - yp) ** 2)))
def da(yt, yp):
    return float(np.mean(np.sign(np.diff(yt)) == np.sign(np.diff(yp))) * 100.0)


def run_one(asset_class: str, model_kind: str, seed: int,
            n: int = 600, n_iter: int = 60) -> dict:
    X, y, n_train = make_dataset(asset_class, n=n, seed=seed)
    n_val = int(0.15 * len(X))
    X_tr, y_tr = X[:n_train], y[:n_train]
    X_va, y_va = X[n_train : n_train + n_val], y[n_train : n_train + n_val]
    X_te, y_te = X[n_train + n_val :],         y[n_train + n_val :]

    if model_kind == "qlstm":
        model = CompactQLSTM(in_features=4, n_blocks=2, seed=seed)
    elif model_kind == "lstm":
        model = CompactLSTM(in_features=4, hidden=7, seed=seed)
    else:
        raise ValueError(model_kind)

    n_pars = model.n_params()
    t0 = time.time()
    rng = np.random.default_rng(seed + 7)
    model, _ = spsa_train(model, X_tr, y_tr, X_va, y_va,
                          n_iter=n_iter, rng=rng)
    dt = time.time() - t0

    y_pred = model.predict_batch(X_te)
    return {
        "model": model_kind, "asset": asset_class, "seed": seed,
        "rmse": rmse(y_te, y_pred), "da": da(y_te, y_pred),
        "n_params": n_pars, "train_sec": dt,
        "y_test": y_te.tolist(), "y_pred": y_pred.tolist(),
    }


